function sz_operator() {
	$name = sz_mod( 'sz_operator', 'ООО «Касимовские Зори»' );
	$ids  = sz_mod( 'sz_operator_id', '' );
	$addr = sz_mod( 'sz_operator_addr', sz_address() );
	$full = $name . ( $ids ? ' (' . $ids . ')' : '' ) . ( $addr ? ', адрес: ' . $addr : '' );
	return array(
		'name'    => $name,
		'full'    => $full,
		'company' => sz_mod( 'sz_company', 'ООО «Касимовские Зори»' ),
	);
}

